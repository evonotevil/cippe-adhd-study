type StudySource = keyof typeof sourceFiles;

export const STUDY_SOURCES: Record<string, string> = sourceFiles;

export interface StudyDay {
  day: number;
  title: string;
  goal: string;
  notes: string[];
  recall: string;
  sources: string[];
  practice?: { topics?: string[]; questionIds?: number[]; count: number; mode?: 'study' | 'exam' };
}

function lesson(
  day: number,
  title: string,
  goal: string,
  sources: StudySource[],
  notes: string[],
  recall: string,
  questions: number[] | number,
  mode: 'study' | 'exam' = 'study',
): StudyDay {
  const practice = typeof questions === 'number'
    ? { count: questions, mode }
    : { count: questions.length, questionIds: questions, mode };

  return { day, title, goal, sources, notes, recall, practice };
}

